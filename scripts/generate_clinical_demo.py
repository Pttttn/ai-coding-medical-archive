def fact(line, day, name, kind="OBSERVATION", status="CONFIRMED", page=None):
    return {
        "type": kind,
        "name": name,
        "valueText": line,
        "eventDate": day,
        "assertionStatus": status,
        "confidence": 1.0,
        "provenance": {"page": page, "sourceText": line},
    }


def record(key, day, title, kind, tags, text, original, facts, page=None):
    return {
        "id": str(uuid5(NAMESPACE_URL, "local-medical-archive/clinical-v1/" + key)),
        "title": title + " · " + day,
        "documentType": kind,
        "documentDate": day,
        "sourceType": "PDF" if page else "TEXT",
        "text": text,
        "pages": [{"pageNumber": page, "text": text}],
        "summary": "Связный синтетический клинический случай. " + title,
        "tags": tags,
        "originalFile": "originals/" + original,
        "facts": facts,
    }


